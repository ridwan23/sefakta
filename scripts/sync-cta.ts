// Membangun src/shared/brand/SeFaktaCta.tsx dari sumber kanonis docs/brand/cta-sefakta.tsx.
// Template CTA tidak berdiri sendiri (memakai scope W, H, clamp, FONT, Ctx), jadi dibungkus dengan scope itu.
//
//   npm run sync:cta               # tulis ulang komponen
//   npm run sync:cta -- --check    # gagal (exit 1) bila komponen tidak sama dengan sumber
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const SOURCE = 'docs/brand/cta-sefakta.tsx';
const TARGET = 'src/shared/brand/SeFaktaCta.tsx';

const HEADER = `// GENERATED by scripts/sync-cta.ts from ${SOURCE}. JANGAN diedit tangan:
// ubah sumber kanonis, lalu jalankan \`npm run sync:cta\`.
import React from 'react';
import {interpolate, spring, Easing, Img, staticFile, useCurrentFrame, useVideoConfig, AbsoluteFill} from 'remotion';
import {FONT_BRAND} from './fonts';

// Scope yang diharapkan template (lihat komentar kepala ${SOURCE}).
const W = 1080;
const H = 1920;
const clamp = {extrapolateLeft: 'clamp', extrapolateRight: 'clamp'} as const;
const FONT = FONT_BRAND;
type Ctx = {
  def: {params: Record<string, unknown>};
  v: {x: number; y: number; opacity: number};
  relSec: number;
  fps: number;
};

/* ---------------- BEGIN verbatim ${SOURCE} ---------------- */
`;

const FOOTER = `
/* ---------------- END verbatim ${SOURCE} ---------------- */

/** Pasang di dalam <Sequence>. \`enterAt\` = detik (relatif Sequence) saat logo mulai muncul;
 *  veil kertas sudah mulai memudar masuk 0,6 dtk sebelumnya, jadi mulai Sequence sedikit lebih awal. */
export const SeFaktaCta: React.FC<{enterAt: number; params?: Record<string, unknown>}> = ({enterAt, params = {}}) => {
  const frame = useCurrentFrame();
  const {fps} = useVideoConfig();
  return (
    <AbsoluteFill style={{pointerEvents: 'none'}}>
      <CtaComp def={{params: {enterAt, centerBlock: true, ...params}}} v={{x: 0.5, y: 0.5, opacity: 1}} relSec={frame / fps} fps={fps} />
    </AbsoluteFill>
  );
};
`;

const generated = HEADER + readFileSync(SOURCE, 'utf8') + FOOTER;
if (process.argv.includes('--check')) {
  const ok = existsSync(TARGET) && readFileSync(TARGET, 'utf8') === generated;
  console.log(ok ? `✓ ${TARGET} sama dengan ${SOURCE}` : `✗ ${TARGET} tidak sama dengan ${SOURCE}. Jalankan: npm run sync:cta`);
  process.exitCode = ok ? 0 : 1;
} else {
  writeFileSync(TARGET, generated);
  console.log(`Ditulis: ${TARGET}`);
}
